# -*- coding: utf-8 -*-
import json
import re

with open('food_vectors.js', 'r', encoding='utf-8') as f:
    text = f.read()

def parse_vectors(text, var_name):
    pattern = r'window\.' + var_name + r'\s*=\s*(\{.*?\});'
    match = re.search(pattern, text, re.DOTALL)
    if not match: return {}
    obj_str = match.group(1)
    return json.loads(obj_str)

food_vectors = parse_vectors(text, "FOOD_VECTORS")
uni_vec = food_vectors.get("ウニ")
if not uni_vec:
    print("ウニ not found in FOOD_VECTORS!")
    exit(1)

def dot_product(v1, v2):
    return sum(a*b for a, b in zip(v1, v2))

