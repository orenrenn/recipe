# Create a mapping of word to vector
num_categories = len(categories)
category_names = list(categories.keys())

vectors_dict = {}

for i, cat_name in enumerate(category_names):
    # Create one-hot vector
    vec = [0.0] * num_categories
    vec[i] = 1.0
    
    for word in categories[cat_name]:
        vectors_dict[word] = vec

# Write to JS
output_path = "food_vectors.js"
with open(output_path, "w", encoding="utf-8") as f:
    f.write("window.FOOD_VECTORS = ")
    json.dump(vectors_dict, f, ensure_ascii=False)
    f.write(";")

