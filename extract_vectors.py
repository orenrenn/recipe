print(f"Extracting vectors for {len(food_words)} words...")

vectors_dict = {}

for word in food_words:
    # Use spaCy to get the 300D vector
    token = nlp(word)
    # Check if vector exists and has non-zero magnitude
    if token.has_vector:
        vec = token.vector
        # Round to 4 decimals to save space
        rounded_vec = [round(float(v), 4) for v in vec]
        
        # Calculate norm to ensure it's not all zeros
        norm = math.sqrt(sum(v*v for v in rounded_vec))
        if norm > 0:
            # Normalize vector to unit length (L2 norm = 1) 
            # This makes cosine similarity just a dot product in JS!
            unit_vec = [round(v / norm, 4) for v in rounded_vec]
            vectors_dict[word] = unit_vec

print(f"Successfully extracted {len(vectors_dict)} vectors.")

# Write to JS
output_path = "food_vectors.js"
with open(output_path, "w", encoding="utf-8") as f:
    f.write("window.FOOD_VECTORS = ")
    json.dump(vectors_dict, f, ensure_ascii=False)
    f.write(";")

print(f"Saved to {output_path}")
